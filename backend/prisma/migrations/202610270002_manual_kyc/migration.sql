CREATE TABLE IF NOT EXISTS manual_kyc (
 id VARCHAR(36) PRIMARY KEY,
 userId VARCHAR(36) NOT NULL UNIQUE,
 status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
 profileCipher LONGTEXT NOT NULL,
 documentCipher LONGBLOB NOT NULL,
 documentMime VARCHAR(50) NOT NULL,
 panLast4 VARCHAR(4) NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 consentVersion VARCHAR(40) NOT NULL,
 consentAt DATETIME NOT NULL,
 submittedAt DATETIME NOT NULL,
 reviewedAt DATETIME NULL,
 reviewedBy VARCHAR(36) NULL,
 note VARCHAR(500) NULL,
 FOREIGN KEY(userId) REFERENCES users(id)
) ENGINE=InnoDB;
