CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(20) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL, role ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER',
 active BOOLEAN NOT NULL DEFAULT true, createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (hash CHAR(64) PRIMARY KEY, userId VARCHAR(36) NOT NULL, expiresAt DATETIME NOT NULL, FOREIGN KEY(userId) REFERENCES users(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL, metal ENUM('Gold','Silver') NOT NULL, active BOOLEAN DEFAULT true, UNIQUE KEY(metal,name)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id VARCHAR(60) PRIMARY KEY, name VARCHAR(160) NOT NULL, metal ENUM('Gold','Silver') NOT NULL, categoryId VARCHAR(36) NOT NULL,
 pricePaise BIGINT UNSIGNED NOT NULL, weight VARCHAR(60) NOT NULL, purity VARCHAR(60) NOT NULL,
 image VARCHAR(2000) NOT NULL DEFAULT '', description TEXT NOT NULL, coinWeight DECIMAL(10,3) NULL,
 stock INT UNSIGNED NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT true, FOREIGN KEY(categoryId) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS shop (userId VARCHAR(36) PRIMARY KEY, cart JSON NOT NULL, favorites JSON NOT NULL, FOREIGN KEY(userId) REFERENCES users(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rates (id VARCHAR(36) PRIMARY KEY, metal ENUM('Gold','Silver') NOT NULL, buyPaise BIGINT UNSIGNED NOT NULL, sellPaise BIGINT UNSIGNED NOT NULL, source VARCHAR(120) NOT NULL, createdAt TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS plans (id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL, months INT NOT NULL, minPaise BIGINT UNSIGNED NOT NULL, active BOOLEAN NOT NULL DEFAULT true) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS kyc (id VARCHAR(36) PRIMARY KEY, userId VARCHAR(36) NOT NULL, status ENUM('PENDING','VERIFIED','REJECTED') NOT NULL, providerRef VARCHAR(190) UNIQUE, consentVersion VARCHAR(40) NOT NULL, consentAt DATETIME NOT NULL, updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, FOREIGN KEY(userId) REFERENCES users(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS accounts (userId VARCHAR(36) PRIMARY KEY, grams BIGINT UNSIGNED NOT NULL DEFAULT 0, reserved BIGINT UNSIGNED NOT NULL DEFAULT 0, CHECK (reserved <= grams), FOREIGN KEY(userId) REFERENCES users(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS subscriptions (id VARCHAR(36) PRIMARY KEY, userId VARCHAR(36) NOT NULL, planId VARCHAR(36) NOT NULL, amountPaise BIGINT UNSIGNED NOT NULL, status ENUM('ACTIVE','PAUSED','CANCELLED') NOT NULL DEFAULT 'ACTIVE', anchorAt DATETIME NOT NULL, paidCount INT NOT NULL DEFAULT 0, nextDue DATETIME NOT NULL, FOREIGN KEY(userId) REFERENCES users(id), FOREIGN KEY(planId) REFERENCES plans(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (id VARCHAR(36) PRIMARY KEY, userId VARCHAR(36) NOT NULL, subscriptionId VARCHAR(36) NOT NULL, reference VARCHAR(120) NOT NULL UNIQUE, rateId VARCHAR(36) NOT NULL, amountPaise BIGINT UNSIGNED NOT NULL, grams BIGINT UNSIGNED NOT NULL, status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING', allocationRef VARCHAR(190) UNIQUE, note VARCHAR(500), createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(userId) REFERENCES users(id), FOREIGN KEY(subscriptionId) REFERENCES subscriptions(id), FOREIGN KEY(rateId) REFERENCES rates(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sales (id VARCHAR(36) PRIMARY KEY, userId VARCHAR(36) NOT NULL, rateId VARCHAR(36) NOT NULL, grams BIGINT UNSIGNED NOT NULL, amountPaise BIGINT UNSIGNED NOT NULL, payoutDetails VARCHAR(500) NOT NULL, status ENUM('PENDING','APPROVED','REJECTED','PAID') DEFAULT 'PENDING', payoutReference VARCHAR(190) UNIQUE, note VARCHAR(500), createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(userId) REFERENCES users(id), FOREIGN KEY(rateId) REFERENCES rates(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ledger (id VARCHAR(36) PRIMARY KEY, userId VARCHAR(36) NOT NULL, kind ENUM('BUY','SELL') NOT NULL, referenceId VARCHAR(36) NOT NULL UNIQUE, grams BIGINT NOT NULL, amountPaise BIGINT UNSIGNED NOT NULL, createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(userId) REFERENCES users(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS enquiries (id VARCHAR(36) PRIMARY KEY, userId VARCHAR(36) NOT NULL, productId VARCHAR(60) NOT NULL, message VARCHAR(1000) NOT NULL, createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit (id VARCHAR(36) PRIMARY KEY, actor VARCHAR(36) NOT NULL, action VARCHAR(60) NOT NULL, referenceId VARCHAR(60) NOT NULL, createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (id INT PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS manual_kyc (
 id VARCHAR(36) PRIMARY KEY,
 userId VARCHAR(36) NOT NULL UNIQUE,
 status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
 profileCipher LONGTEXT NOT NULL,
 documentCipher LONGBLOB NOT NULL,
 documentMime VARCHAR(50) NOT NULL,
 panLast4 VARCHAR(4) NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 consentVersion VARCHAR(40) NOT NULL,
 consentAt DATETIME NOT NULL,
 submittedAt DATETIME NOT NULL,
 reviewedAt DATETIME NULL,
 reviewedBy VARCHAR(36) NULL,
 note VARCHAR(500) NULL,
 FOREIGN KEY(userId) REFERENCES users(id)
) ENGINE=InnoDB;

